/**
 * CLink subclass name → its target namespace (the class's static `link`).
 * e.g. `'CUnitLink' → 'Unit'`. Derived from the link class declarations above so
 * token types declared in data resolve without a duplicated id→namespace map.
 */
export const LINK_CLASS_NAMESPACES: Readonly<Record<string, string>> = Object.freeze(
    Object.fromEntries(
        ALL_LINK_CLASSES
            .filter((c): c is typeof CLink & { link: string } => typeof (c as { link?: unknown }).link === 'string')
            .map(c => [c.name, (c as typeof CLink & { link: string }).link]),
    ),
)

