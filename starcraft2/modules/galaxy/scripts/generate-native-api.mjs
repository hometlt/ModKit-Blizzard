import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'

const inputUrl = new URL('../data/galaxy-script-api.v1.json', import.meta.url)
const outputUrl = new URL('../language/native-api.generated.js', import.meta.url)
const inputBytes = await readFile(inputUrl)
const catalog = JSON.parse(inputBytes.toString('utf8'))

if (catalog.format !== 'modkit-galaxy-script-api' || catalog.formatVersion !== '1.0.0') {
  throw new TypeError('unsupported Galaxy API catalog format')
}
if (!Array.isArray(catalog.functions) || catalog.functions.length !== 3_341) {
  throw new TypeError('the pinned Galaxy API catalog must contain exactly 3341 functions')
}

const declarations = []
const summaries = {}
const seen = new Set()
const reservedNames = new Set([
  'break',
  'breakpoint',
  'const',
  'continue',
  'do',
  'else',
  'false',
  'for',
  'if',
  'include',
  'native',
  'null',
  'return',
  'static',
  'struct',
  'true',
  'typedef',
  'while',
  'void',
  'bool',
  'byte',
  'char',
  'fixed',
  'int',
  'string',
  'text',
  'unit',
])
for (const entry of catalog.functions) {
  if (typeof entry?.interface?.returnType === 'string') {
    reservedNames.add(entry.interface.returnType)
  }
  for (const parameter of entry?.interface?.parameters ?? []) {
    if (typeof parameter?.type === 'string') reservedNames.add(parameter.type)
  }
}
for (const entry of catalog.functions) {
  if (
    typeof entry?.name !== 'string' ||
    entry.name.length === 0 ||
    typeof entry.interface?.declaration !== 'string' ||
    entry.interface.declaration.length === 0
  ) {
    throw new TypeError('Galaxy API entry has no stable name or declaration')
  }
  if (seen.has(entry.name)) throw new TypeError(`duplicate Galaxy API function ${entry.name}`)
  seen.add(entry.name)
  if (
    (entry.kind !== 'native' && entry.kind !== 'script') ||
    typeof entry.interface.returnType !== 'string' ||
    !/^[A-Za-z_]\w*$/u.test(entry.interface.returnType) ||
    !Array.isArray(entry.interface.parameters)
  ) {
    throw new TypeError(`Galaxy API function ${entry.name} has an unsupported interface`)
  }
  const parameterNames = new Set()
  const parameters = entry.interface.parameters.map((parameter, index) => {
    if (
      typeof parameter.type !== 'string' ||
      !/^[A-Za-z_]\w*$/u.test(parameter.type) ||
      typeof parameter.name !== 'string'
    ) {
      throw new TypeError(`Galaxy API function ${entry.name} has an invalid parameter`)
    }
    const candidate = /^[A-Za-z_]\w*$/u.test(parameter.name) ? parameter.name : `lp_${index + 1}`
    const name =
      reservedNames.has(candidate) || parameterNames.has(candidate)
        ? `lp_${index + 1}_${candidate}`
        : candidate
    parameterNames.add(name)
    return `${parameter.type} ${name}`
  })
  declarations.push(
    `${entry.kind === 'native' ? 'native ' : ''}${entry.interface.returnType} ${entry.name}(${parameters.join(', ')});`,
  )
  if (typeof entry.summary === 'string' && entry.summary.trim().length > 0) {
    summaries[entry.name] = entry.summary.trim()
  }
}

const digest = createHash('sha256').update(inputBytes).digest('hex')
const source =
  `// Generated by scripts/generate-native-api.mjs; do not edit by hand.\n` +
  `export const GALAXY_NATIVE_API_CATALOG_DIGEST = ${JSON.stringify(`sha256:${digest}`)}\n` +
  `export const GALAXY_NATIVE_API_FUNCTION_COUNT = ${declarations.length}\n` +
  `export const GALAXY_NATIVE_API_DECLARATIONS = ${JSON.stringify(declarations.join('\n'))}\n` +
  `export const GALAXY_NATIVE_API_SUMMARIES = Object.freeze(${JSON.stringify(summaries, null, 2)})\n`

const current = await readFile(outputUrl, 'utf8').catch(error => {
  if (error?.code === 'ENOENT') return undefined
  throw error
})

if (process.argv.includes('--check')) {
  // The generated adapter is a build artifact and is intentionally not tracked.
  // Parsing and rendering above validate the catalog even in a clean checkout;
  // when a build artifact exists, additionally reject a stale copy.
  if (current !== undefined && current !== source) {
    throw new Error('generated Galaxy API module is stale')
  }
} else if (current !== source) {
  await mkdir(new URL('.', outputUrl), { recursive: true })
  await writeFile(outputUrl, source, 'utf8')
}
